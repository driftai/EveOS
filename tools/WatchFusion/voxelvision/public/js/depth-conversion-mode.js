/** Canonical conversion paths shared by UI, inference, cache and reports. */

export const DEPTH_CONVERSION_MODES = Object.freeze({
  FUSED: 'fused',
  MODEL: 'model',
  LUMA: 'luma'
});

export function normalizeDepthConversionMode(value) {
  const mode = String(value || '').toLowerCase();
  if (mode === DEPTH_CONVERSION_MODES.MODEL) return DEPTH_CONVERSION_MODES.MODEL;
  if (mode === DEPTH_CONVERSION_MODES.LUMA || mode === 'local' || mode === 'luminance') {
    return DEPTH_CONVERSION_MODES.LUMA;
  }
  return DEPTH_CONVERSION_MODES.FUSED;
}

export function conversionUsesAi(value) {
  return normalizeDepthConversionMode(value) !== DEPTH_CONVERSION_MODES.LUMA;
}

export function conversionUsesVideoEvidence(value) {
  return normalizeDepthConversionMode(value) === DEPTH_CONVERSION_MODES.FUSED;
}

export function conversionRenderMode(value) {
  return conversionUsesVideoEvidence(value) ? DEPTH_CONVERSION_MODES.FUSED : DEPTH_CONVERSION_MODES.MODEL;
}

export function descriptorConversionMode(descriptor = {}, environment = null) {
  if (descriptor.conversion) return normalizeDepthConversionMode(descriptor.conversion);
  if (environment?.conversion) return normalizeDepthConversionMode(environment.conversion);
  if (environment?.fusion) return normalizeDepthConversionMode(environment.fusion);
  if (descriptor.backend === 'luma' || descriptor.model === 'local-luminance') {
    return DEPTH_CONVERSION_MODES.LUMA;
  }
  // v1 cache descriptors predate this field and were generated by fused mode.
  return DEPTH_CONVERSION_MODES.FUSED;
}

export function conversionLabel(value) {
  const mode = normalizeDepthConversionMode(value);
  if (mode === DEPTH_CONVERSION_MODES.MODEL) return 'AI model only';
  if (mode === DEPTH_CONVERSION_MODES.LUMA) return 'Local luminance';
  return 'AI + decoded video';
}
